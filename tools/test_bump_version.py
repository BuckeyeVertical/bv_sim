"""Verify release bumps without Cargo, network access, or edits to the checkout."""

from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import tomllib
import unittest

from bump_version import bump, check, next_version


class BumpVersionTest(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory(prefix="bv-sim-version-")
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)
        (self.root / "Cargo.toml").write_text(
            '[workspace]\nmembers = ["crates/launcher", "crates/protocol"]\n\n'
            '[workspace.package]\nversion = "0.1.1" # release\nedition = "2024"\n\n'
            '[workspace.dependencies]\nother = { version = "0.1.1" }\n'
        )
        for name in ("launcher", "protocol"):
            directory = self.root / "crates" / name
            directory.mkdir(parents=True)
            (directory / "Cargo.toml").write_text(
                f'[package]\nname = "{name}"\nversion.workspace = true\n'
            )
        (self.root / "Cargo.lock").write_text(
            '# Generated by Cargo\nversion = 4\n\n'
            '[[package]]\nname = "launcher"\nversion = "0.1.1"\n'
            'dependencies = ["protocol", "other"]\n\n'
            '[[package]]\nname = "protocol"\nversion = "0.1.1"\n\n'
            '[[package]]\nname = "other"\nversion = "0.1.1"\n'
            'source = "registry+https://github.com/rust-lang/crates.io-index"\n'
            'checksum = "unchanged"\n'
        )

    def files(self):
        return {name: (self.root / name).read_bytes() for name in ("Cargo.toml", "Cargo.lock")}

    def test_release_increments_and_explicit_version(self):
        for requested, expected in (
            ("patch", "1.2.10"), ("minor", "1.3.0"), ("major", "2.0.0"), ("3.4.5", "3.4.5")
        ):
            with self.subTest(requested=requested):
                self.assertEqual(next_version("1.2.9", requested), expected)
        for invalid in ("1.2", "v1.2.3", "01.2.3", "1.2.3\n", "0.1.0"):
            with self.subTest(invalid=invalid), self.assertRaises(ValueError):
                next_version("0.1.1", invalid)

    def test_bump_preserves_dependency_versions_and_cargo_comments(self):
        before = tomllib.loads((self.root / "Cargo.lock").read_text())
        version, changed = bump(self.root, "patch")
        self.assertEqual(version, "0.1.2")
        self.assertEqual(set(changed), {Path("Cargo.toml"), Path("Cargo.lock")})
        self.assertFalse((self.root / "VERSION").exists())
        self.assertEqual(check(self.root, "v0.1.2"), "0.1.2")
        manifest = (self.root / "Cargo.toml").read_text()
        self.assertIn('version = "0.1.2" # release', manifest)
        self.assertIn('other = { version = "0.1.1" }', manifest)
        for package in before["package"]:
            if "source" not in package:
                package["version"] = "0.1.2"
        self.assertEqual(tomllib.loads((self.root / "Cargo.lock").read_text()), before)

    def test_check_reports_drift_and_wrong_tag_without_writing(self):
        for tag in ("", "v0.1.1"):
            self.assertEqual(check(self.root, tag), "0.1.1")
        before = self.files()
        with self.assertRaisesRegex(ValueError, "Commit the version bump"):
            check(self.root, "v0.1.2")
        self.assertEqual(self.files(), before)
        lock = self.root / "Cargo.lock"
        lock.write_text(lock.read_text().replace('version = "0.1.1"', 'version = "0.1.0"', 1))
        before = self.files()
        with self.assertRaisesRegex(ValueError, "out of sync in Cargo.lock"):
            check(self.root)
        self.assertEqual(self.files(), before)
        bump(self.root, "0.1.1")
        self.assertEqual(check(self.root), "0.1.1")

    def test_invalid_lockfile_does_not_partially_bump_the_release(self):
        path = self.root / "Cargo.lock"
        path.write_text(path.read_text().replace('name = "protocol"', 'name = "missing"'))
        before = self.files()
        with self.assertRaisesRegex(ValueError, "missing workspace packages: protocol"):
            bump(self.root, "minor")
        self.assertEqual(self.files(), before)

    def test_command_runs_from_another_directory_and_reports_ci_failure(self):
        tools = self.root / "tools"
        tools.mkdir()
        script = tools / "bump_version.py"
        shutil.copy2(Path(__file__).with_name("bump_version.py"), script)

        def run(*args):
            return subprocess.run(
                [sys.executable, str(script), *args], cwd=self.root.parent,
                capture_output=True, text=True,
            )

        bumped = run("patch")
        self.assertEqual(bumped.returncode, 0, bumped.stderr)
        self.assertIn("git tag v0.1.2", bumped.stdout)
        checked = run("--check", "--tag", "v0.1.2")
        self.assertEqual(checked.returncode, 0, checked.stderr)
        self.assertEqual(checked.stdout, "0.1.2\n")
        before = self.files()
        failed = run("--check", "--tag", "v0.1.1")
        self.assertEqual(failed.returncode, 1)
        self.assertIn("expected v0.1.2", failed.stderr)
        self.assertEqual(self.files(), before)


if __name__ == "__main__":
    unittest.main()
